// Generate time slots for a given date and dentist consultations
export const generateTimeSlots = (date: Date, consultations: Consultation[]): TimeSlot[] => {
  const slots: TimeSlot[] = [];
  const DEMO_DATE = new Date(2026, 0, 31);
  const isDemo = date.toDateString() === DEMO_DATE.toDateString();
  
  // Generate slots from 08:00 to 21:30
  for (let hour = 8; hour < 22; hour++) {
    for (let minutes = 0; minutes < 60; minutes += 30) {
      const time = `${hour.toString().padStart(2, '0')}:${minutes.toString().padStart(2, '0')}`;
      
      // Check if there's a consultation at this time
      const consultation = consultations.find(c => 
        c.time === time && 
        c.date.toDateString() === date.toDateString()
      );
      
      // Lunch break
      if (isDemo && (time === '13:00' || time === '13:30')) {
        slots.push({
          time,
          status: 'bloqueado',
          blockReason: 'ALMOÇO',
        });
      } else if (consultation) {
        slots.push({
          time,
          status: 'ocupado',
          consultation,
        });
      } else {
        slots.push({
          time,
          status: 'livre',
        });
      }
    }
  }
  
  return slots;
};
