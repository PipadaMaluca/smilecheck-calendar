export const generateTimeSlots = (date: Date, consultations: Consultation[]): TimeSlot[] => {
  const slots: TimeSlot[] = [];
  const dayConsultations = consultations.filter(
    c => c.date.toDateString() === date.toDateString()
  );

  // Only show consultations on Jan 31 (demo day)
  const isJan31 = date.getDate() === 31 && date.getMonth() === 0 && date.getFullYear() === 2026;
  
  // Fixed hours 8h-22h
  const startHour = 8;
  const endHour = 22;

  for (let hour = startHour; hour < endHour; hour++) {
    for (let minutes = 0; minutes < 60; minutes += 30) {
      const timeString = `${hour.toString().padStart(2, '0')}:${minutes.toString().padStart(2, '0')}`;
      const consultation = isJan31 ? dayConsultations.find(c => c.time === timeString) : undefined;
      
      // Block lunch time (13:00-14:00)
      if (hour === 13) {
        slots.push({
          time: timeString,
          status: 'bloqueado',
          blockReason: 'ALMOÇO',
        });
      } else if (consultation) {
        slots.push({
          time: timeString,
          status: 'ocupado',
          consultation,
        });
      } else {
        slots.push({
          time: timeString,
          status: 'livre',
        });
      }
    }
  }

  return slots;
};
